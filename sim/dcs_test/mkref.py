ci = ci.replace('adsp2101_device::', 'adsp21xx_device::')
tb = cut(cpp, 'void adsp21xx_device::create_tables', '/***************************************************************************\n    CORE EXECUTION LOOP')
ctor = cut(cpp, '\t// set up read register group 0 pointers', '}\n\nadsp2100_device::adsp2100_device')
